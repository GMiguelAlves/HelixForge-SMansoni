// Real bundle conservation and genomic-boundary tests; no fabricated atlas data.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..'),L=require('../analyses/atlas/chipseq_portal/chipseq_logic.js');
const A=JSON.parse(fs.readFileSync(path.join(process.argv[2]||path.join(root,'results/atlas/rnaseq'),'data/chipseq/explorer.json'),'utf8'));
const object=(fields,row)=>Object.fromEntries(fields.map((f,i)=>[f,row[i]]));
const segments=A.consensus.map(r=>object(A.region_fields,r)),peaks=A.library_peaks.map(r=>object(A.region_fields,r)),genes=A.genes.map(r=>object(A.gene_fields,r)),chroms=A.reference.chromosomes;
assert.equal(segments.length,2683);assert.equal(peaks.length,3080);
assert.equal(segments.filter(r=>L.matches(r,{category:'intergenic'})).length,1458);
assert.equal(segments.filter(r=>L.matches(r,{minSupport:'2'})).length,301);
assert.equal(segments.filter(r=>L.matches(r,{minSupport:'3'})).length,94);
assert.equal(segments.filter(r=>L.matches(r,{ambiguity:'not_assessed'})).length,2683);
assert.equal(segments.filter(r=>L.matches(r,{ambiguity:'false'})).length,0);
assert.equal(A.core_segments.length,465);
assert.equal(A.contexts.every(c=>c.method==='nfcore_2_1'&&c.min_libraries===1),true);
assert.equal(peaks.filter(r=>L.matches(r,{stage:'cercaria'})).length,2125);
assert.equal(peaks.filter(r=>L.matches(r,{stage:'sporocyst'})).length,955);
assert.deepEqual(L.parseLocus('SM_V10_1:1-1',chroms),{chrom:'SM_V10_1',start:0,end:1});
assert.deepEqual(L.parseLocus('chr1:1,001-2,000',chroms),{chrom:'SM_V10_1',start:1000,end:2000});
for(const bad of ['1:0-100','1:100-1','1:1-999999999','human:1-10'])assert.throws(()=>L.parseLocus(bad,chroms));
assert.equal(L.overlap({chrom:'a',start:0,end:1},{chrom:'a',start:1,end:2}),false);
assert.equal(L.overlap({chrom:'a',start:1,end:2},{chrom:'a',start:1,end:2}),true);
assert.equal(L.clamp({chrom:'SM_V10_1',start:-500,end:1000},chroms).start,0);
assert.equal(L.clamp({chrom:'SM_V10_1',start:chroms.SM_V10_1-5,end:chroms.SM_V10_1+200},chroms).end,chroms.SM_V10_1);
const locus={chrom:'SM_V10_1',start:1000,end:2000};
assert.deepEqual(L.move(locus,.5,chroms),{chrom:locus.chrom,start:1500,end:2500});
assert.deepEqual(L.zoom(locus,.5,chroms),{chrom:locus.chrom,start:1250,end:1750});
const gene=L.geneMatches(genes,'Smp_244880')[0];assert.equal(gene.id,'Smp_244880');
assert(segments.some(r=>L.overlap(r,{...gene,start:gene.start-4000,end:gene.end+4000})));
assert.equal(L.geneMatches(genes,'not_a_real_gene').length,0);
assert.deepEqual(L.bins([{start:0,end:10,score:2},{start:10,end:20,score:6}],{start:0,end:30},3),[2,6,null]);
assert.deepEqual(L.bins([{start:0,end:2,score:2},{start:2,end:4,score:6}],{start:0,end:4},1),[4]);
assert.equal(A.signal_tracks.length,0);assert.equal(A.signal_status,'NOT_INCLUDED_IN_PUBLIC_SNAPSHOT');
assert.equal(new Set(peaks.map(r=>r.study+'|'+r.library+'|'+r.id)).size,peaks.length);
assert.equal(new Set(segments.map(r=>r.study+'|'+r.id)).size,segments.length);
for(const r of [...segments,...peaks])assert(r.start>=0&&r.end>r.start&&r.end<=chroms[r.chrom]);
console.log('PASS: native conservation; intergenic and stage filters; 1-based/BED boundaries; pan/zoom; gene lookup; signal aggregation and missing-value gaps.');
